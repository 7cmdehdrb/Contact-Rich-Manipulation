"""Desktop Matplotlib viewer: python -m scene_randomization.viewer scenes.npz."""

import argparse

import numpy as np

from .generator import SceneBatch
from .plotting import draw_scene


def main() -> None:
    parser = argparse.ArgumentParser(description="Browse saved push scenes (arrow keys, slider, random)")
    parser.add_argument("input", help="scenes.npz generated by python -m scene_randomization")
    args = parser.parse_args()
    batch = SceneBatch.load(args.input)
    import matplotlib.pyplot as plt
    from matplotlib.widgets import Button, Slider
    fig, ax = plt.subplots(figsize=(13, 6))
    fig.subplots_adjust(bottom=0.22, top=0.88)
    fig.suptitle("RED: Tool/Wrist -y exclusion | GRAY: neighbors | orange B: rear obstacle\n"
                 "purple: target / dashed goal | green: certified finger approach")
    slider = Slider(fig.add_axes((0.13, 0.10, 0.57, 0.04)), "Scene", 0, max(1, len(batch) - 1),
                    valinit=0, valstep=1, valfmt="%d")
    prev = Button(fig.add_axes((0.74, 0.09, 0.06, 0.06)), "Prev")
    nxt = Button(fig.add_axes((0.81, 0.09, 0.06, 0.06)), "Next")
    random = Button(fig.add_axes((0.88, 0.09, 0.07, 0.06)), "Random")
    rng = np.random.default_rng(0)

    def redraw(value):
        ax.clear()
        draw_scene(ax, batch, min(int(value), len(batch) - 1))
        ax.set(xlabel="x (cm)", ylabel="y (cm)")
        fig.canvas.draw_idle()

    def move(step):
        slider.set_val((int(slider.val) + step) % len(batch))

    slider.on_changed(redraw)
    prev.on_clicked(lambda event: move(-1))
    nxt.on_clicked(lambda event: move(1))
    random.on_clicked(lambda event: slider.set_val(int(rng.integers(len(batch)))))

    def key(event):
        if event.key in ("left", "right"):
            move(-1 if event.key == "left" else 1)
        elif event.key == "r":
            slider.set_val(int(rng.integers(len(batch))))

    fig.canvas.mpl_connect("key_press_event", key)
    redraw(0)
    plt.show()


if __name__ == "__main__":
    main()
